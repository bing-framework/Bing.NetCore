async Task CheckJsonTextAsync()
{
    writer.ExecuteSql("CREATE TABLE json_text_rows(\"Id\" integer PRIMARY KEY, \"Payload\" json, \"Document\" jsonb)");
    var jsonModel = models.Single(item => item.EntityType == typeof(JsonTextRow));
    var item = new JsonTextRow { Id = 1, Payload = """{"name":"中文"}""", Document = """{"items":[1,2]}""" };
    var jsonInsert = builder.Insert(item);
    CheckCommand(jsonInsert,
        "Insert Into \"json_text_rows\" (\"Id\", \"Payload\", \"Document\") Values (@_p_0, @_p_1, @_p_2)", jsonModel);
    Check(await writer.ExecuteWriteAsync(jsonInsert) == 1, "generated JSON text insert");

    var queryFactory = scope.ServiceProvider.GetRequiredService<ISqlQueryFactory>();
    using (var query = queryFactory.Create())
    {
        var rows = await query.From<JsonTextRow>().SelectAll().ToListAsync<JsonTextRow>();
        Check(rows.Count == 1 && rows[0].Id == 1 && rows[0].Payload == item.Payload, "generated json text read");
        // jsonb 会规范化空白，验证文档内容。
        using var document = JsonDocument.Parse(rows[0].Document);
        Check(document.RootElement.GetProperty("items").EnumerateArray().Select(value => value.GetInt32())
            .SequenceEqual(new[] { 1, 2 }), "generated jsonb text read");
    }

    item.Payload = "null";
    item.Document = null;
    var jsonUpdate = builder.Update(item);
    CheckCommand(jsonUpdate,
        "Update \"json_text_rows\" Set \"Payload\" = @_p_0, \"Document\" = @_p_1 Where \"Id\" = @_p_2", jsonModel);
    Check(await writer.ExecuteWriteAsync(jsonUpdate) == 1, "generated JSON text update");
    using (var query = queryFactory.Create())
    {
        var rows = await query.From<JsonTextRow>().SelectAll().ToListAsync<JsonTextRow>();
        Check(rows.Count == 1 && rows[0].Payload == "null" && rows[0].Document is null, "JSON null and SQL NULL");
    }
}

async Task CheckTypedJsonAsync()
{
    writer.ExecuteSql("CREATE TABLE typed_json_rows(\"Id\" integer PRIMARY KEY, \"Payload\" json, \"Document\" jsonb)");
    var context = new DatabaseContext { DataSource = new SqlDataSourceDescriptor { DatabaseType = DatabaseType.PgSql } };
    var commandBuilder = new DefaultSqlEntityMutationCommandBuilder(PostgreSqlSqlProvider.Instance, new SqlBuilderServices(
        entityMappingResolver: provider.GetRequiredService<IEntityMappingResolver>(),
        parameterFactory: provider.GetRequiredService<ISqlParameterFactory>(),
        metadataOptions: provider.GetRequiredService<SqlMetadataOptions>(),
        options: new SqlOptions().SetDatabaseContext(context),
        entityModelMetadataProvider: provider.GetRequiredService<IEntityModelMetadataProvider>()));
    var jsonModel = models.Single(model => model.EntityType == typeof(TypedJsonRow));
    var row = new TypedJsonRow
    {
        Id = 1,
        Payload = new JsonProfile { Name = "中文", Items = new[] { 1 } },
        Document = new JsonProfile { Name = "jsonb", Items = new[] { 2, 3 } }
    };
    CheckCommand(commandBuilder.Insert(row),
        "Insert Into \"typed_json_rows\" (\"Id\", \"Payload\", \"Document\") Values (@_p_0, @_p_1, @_p_2)", jsonModel);
    Check(await writer.InsertAsync(row) == 1, "generated typed JSON insert");

    var queryFactory = scope.ServiceProvider.GetRequiredService<ISqlQueryFactory>();
    using (var query = queryFactory.Create())
    {
        var result = (await query.From<TypedJsonRow>().Select<TypedJsonRow>(item => new { item.Id, item.Payload, item.Document }).ToListAsync<TypedJsonRow>()).Single();
        Check(result.Id == 1 && result.Payload.Name == "中文" && result.Payload.Items.SequenceEqual(new[] { 1 }),
            "generated typed json read");
        Check(result.Document.Name == "jsonb" && result.Document.Items.SequenceEqual(new[] { 2, 3 }),
            "generated typed jsonb read");
    }

    row.Payload = null;
    row.Document = new JsonProfile { Name = "updated", Items = Array.Empty<int>() };
    CheckCommand(commandBuilder.Update(row),
        "Update \"typed_json_rows\" Set \"Payload\" = @_p_0, \"Document\" = @_p_1 Where \"Id\" = @_p_2", jsonModel);
    Check(await writer.UpdateAsync(row) == 1, "generated typed JSON update");
    writer.ExecuteSql("INSERT INTO typed_json_rows(\"Id\", \"Payload\") VALUES (2, 'null'::json)");
    using (var query = queryFactory.Create())
    {
        var rows = await query.From<TypedJsonRow>().Select<TypedJsonRow>(item => new { item.Id, item.Payload, item.Document }).ToListAsync<TypedJsonRow>();
        var updated = rows.Single(item => item.Id == 1);
        Check(updated.Payload is null && updated.Document.Name == "updated" && updated.Document.Items.Length == 0,
            "typed JSON update and SQL NULL");
        var jsonNull = rows.Single(item => item.Id == 2);
        Check(jsonNull.Payload is null && jsonNull.Document is null, "JSON null converts to CLR null");
    }
    using (var connection = new NpgsqlConnection(connectionString))
    {
        await connection.OpenAsync();
        using var command = new NpgsqlCommand("SELECT \"Payload\" IS NULL FROM typed_json_rows WHERE \"Id\" = 1", connection);
        Check((await command.ExecuteScalarAsync()) is true, "CLR null is stored as SQL NULL");
    }
}

async Task CheckBuiltInRangesAsync()
{
    writer.ExecuteSql("""
        CREATE TABLE range_rows(
            "Id" integer PRIMARY KEY, "Bounds" int4range, "Periods" int4multirange,
            "BigBounds" int8range, "BigPeriods" int8multirange, "NumericBounds" numrange, "NumericPeriods" nummultirange,
            "DateBounds" daterange, "DatePeriods" datemultirange, "TimestampBounds" tsrange, "TimestampPeriods" tsmultirange,
            "UtcBounds" tstzrange, "UtcPeriods" tstzmultirange)
        """);
    var model = models.Single(item => item.EntityType == typeof(RangeRow));
    var big = new NpgsqlRange<long>(4_000_000_000L, true, 4_000_000_020L, false);
    var numeric = new NpgsqlRange<decimal>(1.25m, true, 3.75m, false);
    var dates = new NpgsqlRange<DateTime>(new DateTime(2026, 11, 20), true, new DateTime(2026, 11, 23), false);
    var local = new DateTime(2026, 11, 20, 9, 0, 0, DateTimeKind.Unspecified);
    var utc = new DateTime(2026, 11, 20, 1, 0, 0, DateTimeKind.Utc);
    var timestamp = new NpgsqlRange<DateTime>(local, true, local.AddMinutes(30), false);
    var timestampTz = new NpgsqlRange<DateTime>(utc, true, utc.AddMinutes(30), false);
    var row = new RangeRow
    {
        Id = 1,
        Bounds = new NpgsqlRange<int>(1, true, 4, false),
        Periods = new[] { new NpgsqlRange<int>(2, true, 5, false), new NpgsqlRange<int>(8, true, 10, false) },
        BigBounds = big, BigPeriods = new[] { big },
        NumericBounds = numeric, NumericPeriods = new[] { numeric },
        DateBounds = dates, DatePeriods = new[] { dates },
        TimestampBounds = timestamp, TimestampPeriods = new[] { timestamp },
        UtcBounds = timestampTz, UtcPeriods = new[] { timestampTz }
    };
    CheckCommand(builder.Insert(row),
        "Insert Into \"range_rows\" (\"Id\", \"Bounds\", \"Periods\", \"BigBounds\", \"BigPeriods\", \"NumericBounds\", \"NumericPeriods\", " +
        "\"DateBounds\", \"DatePeriods\", \"TimestampBounds\", \"TimestampPeriods\", \"UtcBounds\", \"UtcPeriods\") " +
        "Values (@_p_0, @_p_1, @_p_2, @_p_3, @_p_4, @_p_5, @_p_6, @_p_7, @_p_8, @_p_9, @_p_10, @_p_11, @_p_12)", model);
    Check(await writer.InsertAsync(row) == 1, "generated range insert");

    var queryFactory = scope.ServiceProvider.GetRequiredService<ISqlQueryFactory>();
    using (var query = queryFactory.Create())
    {
        var result = (await SelectRangeRow(query).ToListAsync<RangeRow>()).Single();
        Check(result.Bounds == row.Bounds && result.Periods.SequenceEqual(row.Periods), "int4 roundtrip");
        Check(result.BigBounds == big && result.BigPeriods.SequenceEqual(row.BigPeriods), "int8 roundtrip");
        Check(result.NumericBounds == numeric && result.NumericPeriods.SequenceEqual(row.NumericPeriods), "numeric roundtrip");
        Check(result.DateBounds == dates && result.DatePeriods.SequenceEqual(row.DatePeriods), "date roundtrip");
        Check(result.TimestampBounds == timestamp && result.TimestampPeriods.SequenceEqual(row.TimestampPeriods) &&
            result.TimestampBounds.Value.LowerBound.Kind == DateTimeKind.Unspecified, "timestamp roundtrip");
        Check(result.UtcBounds == timestampTz && result.UtcPeriods.SequenceEqual(row.UtcPeriods) &&
            result.UtcBounds.Value.LowerBound.Kind == DateTimeKind.Utc, "timestamptz roundtrip");
    }

    var cleared = new RangeRow { Id = 1, Periods = Array.Empty<NpgsqlRange<int>>() };
    CheckCommand(builder.Update(cleared),
        "Update \"range_rows\" Set \"Bounds\" = @_p_0, \"Periods\" = @_p_1, \"BigBounds\" = @_p_2, \"BigPeriods\" = @_p_3, " +
        "\"NumericBounds\" = @_p_4, \"NumericPeriods\" = @_p_5, \"DateBounds\" = @_p_6, \"DatePeriods\" = @_p_7, " +
        "\"TimestampBounds\" = @_p_8, \"TimestampPeriods\" = @_p_9, \"UtcBounds\" = @_p_10, \"UtcPeriods\" = @_p_11 Where \"Id\" = @_p_12", model);
    Check(await writer.UpdateAsync(cleared) == 1, "generated range update");
    using (var query = queryFactory.Create())
    {
        var result = await SelectRangeRow(query).ToAsync<RangeRow>();
        Check(result.Bounds is null && result.Periods.Length == 0 && result.BigBounds is null && result.BigPeriods is null &&
            result.NumericBounds is null && result.NumericPeriods is null && result.DateBounds is null && result.DatePeriods is null &&
            result.TimestampBounds is null && result.TimestampPeriods is null && result.UtcBounds is null && result.UtcPeriods is null,
            "SQL NULL range, SQL NULL multirange and empty multirange");
    }
}

static SqlLambdaQuery SelectRangeRow(ISqlQuery query) => query.From<RangeRow>()
    .Select<RangeRow>(row => new
    {
        row.Id, row.Bounds, row.Periods, row.BigBounds, row.BigPeriods, row.NumericBounds, row.NumericPeriods,
        row.DateBounds, row.DatePeriods, row.TimestampBounds, row.TimestampPeriods, row.UtcBounds, row.UtcPeriods
    });

async Task CheckExplicitCompositeAsync()
{
    writer.ExecuteSql("CREATE TYPE composite_value AS (code bigint, label text)");
    writer.ExecuteSql("CREATE TABLE composite_rows(id integer PRIMARY KEY, details composite_value)");
    const string insert = "INSERT INTO composite_rows(id, details) VALUES (@Id, ROW(@Code, @Label)::composite_value)";
    const string select = "SELECT id AS \"Id\", (details).code AS \"Code\", (details).label AS \"Label\" FROM composite_rows ORDER BY id";
    var first = new CompositeFields { Id = 1, Code = 4_000_000_001L, Label = "明细" };
    var second = new CompositeFields { Id = 2, Code = 4_000_000_002L };
    Check(await writer.ExecuteSqlAsync(insert, first) == 1 && await writer.ExecuteSqlAsync(insert, second) == 1,
        "explicit composite insert with generated parameters");
    using var query = scope.ServiceProvider.GetRequiredService<ISqlQueryFactory>().Create();
    var rows = await query.Sql(select).ToListAsync<CompositeFields>();
    Check(rows.Count == 2 && rows[0].Id == 1 && rows[0].Code == first.Code && rows[0].Label == first.Label &&
        rows[1].Id == 2 && rows[1].Code == second.Code && rows[1].Label is null,
        "explicit composite projection and SQL NULL member");
}

static void CheckCommand(SqlWriteCommand command, string expected, EntityModelMetadata model)
{
    Check(command.Sql == expected && command.IsGeneratedExecution &&
        ReferenceEquals(command.Sql, model.GeneratedMutationSql?.Invoke("bing.postgresql", command.OperationKind)),
        "generated SQL and binder: " + expected);
}

static void Check(bool condition, string message)
{
    if (!condition) throw new InvalidOperationException(message);
}

